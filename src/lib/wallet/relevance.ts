/**
 * Location relevance for Wallet passes — pure, platform-spec builders (no network).
 *
 * Apple Wallet (PassKit, pass.json):
 *   - `locations`: up to 10 { latitude, longitude, altitude?, relevantText? }.
 *   - `maxDistance` (meters): can only REDUCE the system's default relevance distance for the pass style;
 *     iOS decides if/when the pass is surfaced on the Lock Screen. No push is involved and the issuer
 *     never learns the user's position.
 * Google Wallet (LoyaltyClass / LoyaltyObject):
 *   - `merchantLocations`: up to 10 { latitude, longitude }. Google decides if/when to show a nearby
 *     notification (requires the user's location + Wallet notifications; Google rate-limits them).
 *     The geofence text is generated by Google; a campaign message can be shown in the pass `messages`.
 */
export const MAX_WALLET_LOCATIONS = 10;

export type GeoLocation = { id: string; name: string; latitude: number | null; longitude: number | null; geo_enabled: boolean; geo_radius_m: number; geo_message: string | null; is_active: boolean };
export type ActiveLocationCampaign = { id: string; message: string; location_ids: string[]; program_ids: string[] | null; starts_at: string; ends_at: string };

export type AppleLocation = { latitude: number; longitude: number; relevantText?: string };
export type GoogleMerchantLocation = { latitude: number; longitude: number };

const round6 = (n: number) => Math.round(n * 1e6) / 1e6;

/** Locations eligible for relevance: active, geofencing on, with valid coordinates. Campaign locations first. */
export function eligibleLocations(locations: GeoLocation[], campaign?: ActiveLocationCampaign | null): (GeoLocation & { latitude: number; longitude: number })[] {
  const ok = locations.filter((l): l is GeoLocation & { latitude: number; longitude: number } =>
    l.is_active && l.geo_enabled && typeof l.latitude === "number" && typeof l.longitude === "number" && Math.abs(l.latitude) <= 90 && Math.abs(l.longitude) <= 180);
  const inCampaign = new Set(campaign?.location_ids ?? []);
  return [...ok.filter((l) => inCampaign.has(l.id)), ...ok.filter((l) => !inCampaign.has(l.id))].slice(0, MAX_WALLET_LOCATIONS);
}

/** The campaign that applies right now to a given program (latest start wins). */
export function currentCampaign(campaigns: (ActiveLocationCampaign & { status: string })[], programId: string, now = new Date()) {
  return campaigns
    .filter((c) => c.status === "active" && new Date(c.starts_at) <= now && new Date(c.ends_at) > now && (!c.program_ids || c.program_ids.includes(programId)))
    .sort((a, b) => +new Date(b.starts_at) - +new Date(a.starts_at))[0] ?? null;
}

export function appleRelevance(locations: GeoLocation[], opts: { merchantName: string; campaign?: ActiveLocationCampaign | null }) {
  const list = eligibleLocations(locations, opts.campaign);
  if (!list.length) return {};
  const inCampaign = new Set(opts.campaign?.location_ids ?? []);
  const text = (l: GeoLocation) => (inCampaign.has(l.id) ? opts.campaign!.message : l.geo_message || `${opts.merchantName} · ${l.name}`).slice(0, 120);
  return {
    locations: list.map((l): AppleLocation => ({ latitude: round6(l.latitude), longitude: round6(l.longitude), relevantText: text(l) })),
    maxDistance: Math.max(...list.map((l) => l.geo_radius_m)),
  };
}

export function googleRelevance(locations: GeoLocation[], opts: { campaign?: ActiveLocationCampaign | null; campaignHeader?: string }) {
  const list = eligibleLocations(locations, opts.campaign);
  const out: { merchantLocations?: GoogleMerchantLocation[]; messages?: { id: string; header: string; body: string; messageType: "TEXT"; displayInterval: { start: { date: string }; end: { date: string } } }[] } = {};
  if (list.length) out.merchantLocations = list.map((l) => ({ latitude: round6(l.latitude), longitude: round6(l.longitude) }));
  if (opts.campaign) {
    out.messages = [{
      id: `loc-campaign-${opts.campaign.id}`, header: (opts.campaignHeader ?? "Offre").slice(0, 60), body: opts.campaign.message,
      messageType: "TEXT", displayInterval: { start: { date: new Date(opts.campaign.starts_at).toISOString() }, end: { date: new Date(opts.campaign.ends_at).toISOString() } },
    }];
  }
  return out;
}

/** Great-circle distance in meters (used only for merchant-side map validation, never for customers). */
export function distanceMeters(a: { lat: number; lng: number }, b: { lat: number; lng: number }) {
  const R = 6_371_000, toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat), dLng = toRad(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}
